import 'server-only';
import { cookies } from 'next/headers';
import { readDb } from './db';
import { STRINGS, type StringKey } from './strings';
import { LANG_COOKIE, isLang, type Lang } from './i18n-shared';

export { LANGS, LANG_COOKIE, HTML_LANG, isLang, type Lang } from './i18n-shared';

/**
 * Two languages, one ledger.
 *
 * Interface text is hand-written in both (`src/lib/strings.ts`) — machine
 * translation of a term of art like "value at MRP" is exactly where it goes
 * wrong. Data text is a different problem: the consumer API and TNGIS both
 * publish English only, so there is nothing Tamil upstream to mirror. What Tamil
 * exists for district and shop names is generated by `npm run translate` into
 * `name_i18n`, tagged with how it was produced, and read back here.
 */

/** The reader's language, from their cookie. English until they choose otherwise. */
export async function getLang(): Promise<Lang> {
  const v = (await cookies()).get(LANG_COOKIE)?.value;
  return isLang(v) ? v : 'en';
}

export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

/**
 * Split a translated string around one placeholder, so a React node can go where
 * the placeholder was. Needed wherever the substitution is not plain text — a
 * phone number that has to be set in the mono face, a link — and the surrounding
 * words move relative to it between languages.
 */
export function splitAt(text: string, token: string): [string, string] {
  const marker = `{${token}}`;
  const i = text.indexOf(marker);
  return i < 0 ? [text, ''] : [text.slice(0, i), text.slice(i + marker.length)];
}

/**
 * Interface translator. Falls back to English for any key not yet carried in
 * Tamil, so a missing string degrades to readable rather than to a raw key.
 */
export function translator(lang: Lang): Translate {
  return (key, vars) => {
    const entry = STRINGS[key];
    let out = (entry && (entry[lang] ?? entry.en)) ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
    return out;
  };
}

// ─────────────────────────── data names ───────────────────────────

export type Entity = 'district' | 'taluk' | 'product_line' | 'sku' | 'supplier' | 'liquor_type';

export interface Localised {
  /** Translated text, or the English fallback when none exists. */
  (entity: Entity, id: number | null | undefined, fallback: string | null): string;
}

interface NameRow { entity: string; entity_id: number; text: string }

/**
 * The whole Tamil name map is ~3,600 short rows, so it is loaded once per
 * process and held. A per-row lookup would mean an extra join on every list
 * query; a cached map costs a few hundred kilobytes and nothing per request.
 * The cache is keyed by language so switching does not have to evict.
 */
const cache = new Map<Lang, Map<string, string>>();

function nameMap(lang: Lang): Map<string, string> {
  const hit = cache.get(lang);
  if (hit) return hit;
  const map = new Map<string, string>();
  if (lang !== 'en') {
    try {
      const rows = readDb()
        .prepare('SELECT entity, entity_id, text FROM name_i18n WHERE lang = ?')
        .all(lang) as NameRow[];
      for (const r of rows) map.set(`${r.entity}:${r.entity_id}`, r.text);
    } catch {
      // Translations not generated yet — every lookup falls through to English.
    }
  }
  cache.set(lang, map);
  return map;
}

export function localiser(lang: Lang): Localised {
  const map = nameMap(lang);
  return (entity, id, fallback) => {
    if (id == null) return fallback ?? '—';
    return map.get(`${entity}:${id}`) ?? fallback ?? '—';
  };
}

/**
 * Everything a page needs in one await: the reader's language, the interface
 * translator, and the data-name localiser.
 */
export async function page(): Promise<{ lang: Lang; t: Translate; L: Localised }> {
  const lang = await getLang();
  return { lang, t: translator(lang), L: localiser(lang) };
}
